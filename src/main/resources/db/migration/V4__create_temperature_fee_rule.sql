CREATE TABLE temperature_fee_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_type VARCHAR(20) NOT NULL,
    min_temperature DOUBLE PRECISION,
    max_temperature DOUBLE PRECISION,
    min_inclusive BOOLEAN NOT NULL,
    max_inclusive BOOLEAN NOT NULL,
    amount DECIMAL(10, 2) NOT NULL,
    valid_from TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    valid_to TIMESTAMP(6) WITH TIME ZONE,

    CONSTRAINT chk_temperature_fee_amount
        CHECK (amount >= 0),

    CONSTRAINT chk_temperature_fee_bounds CHECK (
        (min_temperature IS NOT NULL OR max_temperature IS NOT NULL)
            AND (
            min_temperature IS NULL
                OR max_temperature IS NULL
                OR min_temperature < max_temperature
            )
        ),

    CONSTRAINT chk_temperature_fee_validity
        CHECK (valid_to IS NULL OR valid_to > valid_from)
);