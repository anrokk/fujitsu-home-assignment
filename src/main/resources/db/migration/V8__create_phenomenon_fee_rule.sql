CREATE TABLE phenomenon_fee_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_type VARCHAR(20) NOT NULL,
    phenomenon_category VARCHAR(20) NOT NULL,
    amount DECIMAL(10, 2),
    forbidden BOOLEAN NOT NULL,
    valid_from TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    valid_to TIMESTAMP(6) WITH TIME ZONE,

    CONSTRAINT chk_phenomenon_fee_outcome CHECK (
        (forbidden = TRUE AND amount IS NULL)
            OR
        (forbidden = FALSE AND amount IS NOT NULL AND amount >= 0)
        ),

    CONSTRAINT chk_phenomenon_fee_validity
        CHECK (valid_to IS NULL OR valid_to > valid_from)
);