CREATE TABLE wind_fee_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_type VARCHAR(20) NOT NULL,
    min_wind_speed DOUBLE PRECISION,
    max_wind_speed DOUBLE PRECISION,
    min_inclusive BOOLEAN NOT NULL,
    max_inclusive BOOLEAN NOT NULL,
    amount DECIMAL(10, 2),
    forbidden BOOLEAN NOT NULL,
    valid_from TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    valid_to TIMESTAMP(6) WITH TIME ZONE,

    CONSTRAINT chk_wind_fee_bounds CHECK (
        (min_wind_speed IS NOT NULL OR max_wind_speed IS NOT NULL)
            AND (
            min_wind_speed IS NULL
                OR max_wind_speed IS NULL
                OR min_wind_speed < max_wind_speed
            )
        ),

    CONSTRAINT chk_wind_fee_outcome CHECK (
        (forbidden = TRUE AND amount IS NULL)
            OR
        (forbidden = FALSE AND amount IS NOT NULL AND amount >= 0)
        ),

    CONSTRAINT chk_wind_fee_validity
        CHECK (valid_to IS NULL OR valid_to > valid_from)
);